const opp = q => p.send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: q.x, y: q.y, button: 'left', buttons: 0, clickCount: 1 });
const dra = async pts => { const P = []; for (const [x, y] of pts) P.push(await W(x, y)); await flytt(P[0]); await ned(P[0]); await sov(30); for (const q of P.slice(1)) await flytt(q, 1); await opp(P[P.length - 1]); await sov(400); };
